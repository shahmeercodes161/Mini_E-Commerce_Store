// Safe image resolver: automatically replaces broken /vite.svg or empty URLs with real product photo
export function resolveProductImage(product) {
  if (!product) return '';
  const url = product.imageUrl;
  if (url && !url.includes('vite.svg') && !url.includes('placeholder.com')) {
    return url;
  }
  return PRODUCT_IMAGE_MAP[product.name] || url || '';
}
